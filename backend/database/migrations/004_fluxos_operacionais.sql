-- Novos fluxos: candidatos por vaga, importações e entregas do Kanban.
-- Contadores legados de vagas permanecem intactos; indicadores passam a usar vínculos reais.
CREATE TABLE candidatos_vaga (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vaga_id INTEGER NOT NULL REFERENCES vagas(id_vaga) ON DELETE CASCADE,
    nome VARCHAR(150) NOT NULL CHECK (btrim(nome) <> ''),
    email VARCHAR(150) NOT NULL CHECK (btrim(email) <> ''),
    telefone VARCHAR(40),
    perfil_ideal BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(20) NOT NULL DEFAULT 'inscrito'
        CHECK (status IN ('inscrito', 'em_analise', 'aprovado', 'reprovado', 'erro')),
    motivo_erro VARCHAR(500),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((status = 'erro' AND motivo_erro IS NOT NULL AND btrim(motivo_erro) <> '')
        OR (status <> 'erro' AND motivo_erro IS NULL))
);
CREATE UNIQUE INDEX uq_candidato_vaga_email ON candidatos_vaga(vaga_id, lower(email));

CREATE TABLE importacoes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    autor_id INTEGER NOT NULL REFERENCES usuarios(id_usuario),
    chave VARCHAR(100) NOT NULL,
    checksum CHAR(64) NOT NULL,
    quantidade INTEGER NOT NULL CHECK (quantidade BETWEEN 1 AND 1000),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (autor_id, chave)
);
CREATE TABLE importacoes_vagas (
    importacao_id INTEGER NOT NULL REFERENCES importacoes(id),
    vaga_id INTEGER NOT NULL REFERENCES vagas(id_vaga),
    PRIMARY KEY (importacao_id, vaga_id)
);

CREATE TABLE entregas_tarefa (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarefa_id INTEGER NOT NULL REFERENCES tarefas(id_tarefa),
    responsavel_id INTEGER NOT NULL REFERENCES usuarios(id_usuario),
    autor_id INTEGER NOT NULL REFERENCES usuarios(id_usuario),
    projeto_id INTEGER REFERENCES projetos(id_projeto),
    concluido_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_entregas_periodo ON entregas_tarefa(concluido_em, responsavel_id);
