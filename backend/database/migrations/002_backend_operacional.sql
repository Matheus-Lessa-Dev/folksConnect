);
CREATE TABLE anexos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarefa_id INTEGER NOT NULL REFERENCES tarefas(id_tarefa) ON DELETE CASCADE,
    nome VARCHAR(255) NOT NULL,
    content_type VARCHAR(150) NOT NULL,
    tamanho INTEGER NOT NULL CHECK (tamanho > 0 AND tamanho <= 10485760),
    conteudo BYTEA NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (octet_length(conteudo) = tamanho)
);
CREATE INDEX idx_anexos_tarefa ON anexos(tarefa_id);

