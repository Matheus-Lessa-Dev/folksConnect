CREATE TABLE avancos_tarefa (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarefa_id INTEGER NOT NULL REFERENCES tarefas(id_tarefa),
    etapa_anterior_id INTEGER NOT NULL REFERENCES etapas_funil(id),
    etapa_id INTEGER NOT NULL REFERENCES etapas_funil(id),
